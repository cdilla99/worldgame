// Input: Natural Earth's public-domain ne_50m_admin_0_map_units.geojson.
// Generates only Explorer features; country and economics files are untouched.
import fs from 'node:fs';
const source = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const antarctica = source.features.find(feature => feature.properties?.ADM0_A3 === 'ATA' || feature.properties?.ADMIN === 'Antarctica');
if (!antarctica) throw new Error('Antarctica is missing from the Natural Earth source.');
const polygons = antarctica.geometry.type === 'MultiPolygon' ? antarctica.geometry.coordinates : [antarctica.geometry.coordinates];
const outline = polygons.map(polygon => polygon.map(ring => {
  const points = [];
  for (let index = 0; index < ring.length - 1; index++) {
    const point = ring[index];
    const previous = points.at(-1);
    if (!previous || Math.hypot(point[0] - previous[0], point[1] - previous[1]) >= 0.12) {
      points.push(point.map(value => Math.round(value * 1000) / 1000));
    }
  }
  if (points.length < 3) return ring.map(point => point.map(value => Math.round(value * 1000) / 1000));
  return [...points, points[0]];
}));
const record = { i: 2001, c: 'AQ', x: 0, y: -90, s: 0, f: 1, p: outline };
fs.writeFileSync('assets/globe-features.js', `/* Natural Earth 1:50m, public domain. Generated by scripts/build-globe-features.mjs. */\nwindow.GeoWarsGlobeFeatures=${JSON.stringify([record])};\n`);
console.log(`Generated Antarctica: ${outline.length} polygons.`);
